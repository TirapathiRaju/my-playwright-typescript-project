const { test, expect } = require('@playwright/test');
test('Assessment 2 verify refund eligibility for single-ticket bookings', async ({ page }) => {
    await page.goto('https://eventhub.rahulshettyacademy.com/login');
    await page.waitForLoadState('networkidle');
    await page.getByPlaceholder("you@email.com").fill("tirapathi.raju@gmail.com");
    await page.locator('#password').fill("Test@123");
    await page.getByRole("button", { name: 'Sign In' }).click();
    await page.waitForLoadState('networkidle');
    await expect(page.getByRole('link', { name: 'Browse Events →' })).toBeVisible();
    await page.locator('#nav-events').click();
    await page.waitForLoadState('networkidle');
    await expect(page.getByTestId('event-card').first()).toBeVisible();
    await page.getByTestId('event-card').first().getByTestId('book-now-btn').click();
    await page.waitForLoadState('networkidle');
    await page.locator('#customerName').fill('Tirapathi Raju');
    await page.locator('#customer-email').fill('tirapathi.raju@gmail.com');
    await page.locator('#phone').fill('1234567890');
    await page.getByRole('button', { name: 'Confirm Booking' }).click();
    await page.waitForLoadState('networkidle');
    await page.getByRole('button', { name: 'View My Bookings' }).click();
    await page.waitForLoadState('networkidle');
    await page.getByRole('link', { name: 'View Details' }).first().click();
    await page.waitForLoadState('networkidle');
    await expect(page.getByText('Booking Information')).toBeVisible();
    const bookingRef = await page.locator('span.font-mono.font-bold').innerText();
    const eventTitle = await page.locator('h1').innerText();
    expect(bookingRef.charAt(0)).toBe(eventTitle.charAt(0));
    await page.locator('#check-refund-btn').click();
    await expect(page.locator('#refund-spinner')).toBeVisible();
    await expect(page.locator('#refund-spinner')).not.toBeVisible({ timeout: 6000 });
    const refundMessage = page.locator('#refund-result');
    await expect(refundMessage).toBeVisible();
    await expect(refundMessage).toContainText('Eligible for refund.');
    await expect(refundMessage).toContainText(' Single-ticket bookings qualify for a full refund.');
});


