const {test, expect} = require('@playwright/test');
const { timeout } = require('../playwright.config');
test('Assessment1', async({browser}) => {
    const context = await browser.newContext();
    const page = await context.newPage();
    const eventTitle = `Test Event ${Date.now()}`;
    await page.goto('https://eventhub.rahulshettyacademy.com/login');
    await page.waitForLoadState('networkidle');
    await page.getByPlaceholder("you@email.com").fill("tirapathi.raju@gmail.com");
    await page.locator('#password').fill("Test@123");
    await page.getByRole("button", {name: 'Sign In'}).click();
    await page.waitForLoadState('networkidle');
    await expect(page.getByRole('link', { name: 'Browse Events →' })).toBeVisible();
    await page.getByRole('button', { name: 'Admin' }).click();
    await page.getByRole('link', {name: 'Manage Events'}).first().click();
    await page.waitForLoadState('networkidle');
    await expect(page.getByRole('button', { name: '+ Add Event' })).toBeVisible();
    await page.getByPlaceholder("Event title").fill(eventTitle);
    await page.getByPlaceholder("Describe the event…").fill("Pongal Event is a harvest festival celebrated in South India.");
    await page.selectOption('select#category', 'Festival');
    await page.getByLabel('City*').fill("Rajahmundry");
    await page.locator('#venue').fill('Godavari River Bank');
    await page.getByLabel("Event Date & Time").fill("2027-01-13T10:00");
    await page.getByLabel("Price ($)").fill("1000.00");
    await page.getByLabel("Total Seats").fill("100");
    await page.locator('button[type="submit"]').click();
    await page.waitForLoadState('networkidle');
    await expect(page.getByText('Event created!', { exact: true })).toBeVisible();
    await page.locator('#nav-events').click();
    const eventCards = page.locator('#event-card');
    await eventCards.first().waitFor();
    await expect(eventCards.first()).toBeVisible();
    const targetEventCard = eventCards.filter({hasText: eventTitle}).first();
    await expect(targetEventCard).toBeVisible({timeout:5000});
    const seatsBeforeBooking = parseInt(await targetEventCard.getByText('seat').first().innerText());
    console.log(`Seats available before booking: ${seatsBeforeBooking}`);
    await targetEventCard.getByTestId('book-now-btn').click();
    await page.waitForLoadState('networkidle');
    const ticketCount = page.locator('#ticket-count');
    await expect(ticketCount).toHaveText('1');
    await page.getByLabel('Full Name').fill('Tirapathi Raju');
    await page.getByLabel('Email').fill('tirapathi.raju@gmail.com');
    await page.getByLabel('Phone Number').fill('1234567890');
    await page.getByRole('button', {name: 'Confirm Booking'}).click();
    const bookingRef1 = page.locator('.booking-ref').first();
    await expect(bookingRef1).toBeVisible();
    const bookingRef = (await bookingRef1.innerText()).trim();
    expect(bookingRef.charAt(0)).toBe(eventTitle.trim().charAt(0).toUpperCase());
    console.log(`Booking Confirmation Reference: ${bookingRef}`);
    await page.getByRole('button', {name: 'View My Bookings'}).click();
    await page.waitForLoadState('networkidle');
    const bookingCards = page.locator('#booking-card');
    await bookingCards.first().waitFor();
    await expect(bookingCards.first()).toBeVisible();
    const matchedBookingCard = bookingCards.filter({has: page.locator('.booking-ref', { hasText: bookingRef })});
    await expect(matchedBookingCard).toBeVisible({timeout:5000});
    await expect(matchedBookingCard).toContainText(eventTitle);
    console.log(`Booking for event "${eventTitle}" is successfully verified in the "My Bookings" section.`);
    await page.locator('#nav-events').click();
    await expect(eventCards.first()).toBeVisible();
    const updatedCard = eventCards.filter({hasText: eventTitle}).first();
    await expect(updatedCard).toBeVisible({timeout:5000});
    const seatsAfterBooking = parseInt(await updatedCard.getByText('seat').first().innerText());
    console.log(`Seats available after booking: ${seatsAfterBooking}`);
    expect(seatsAfterBooking).toBe(seatsBeforeBooking - 1);

});